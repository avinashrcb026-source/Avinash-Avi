// Generate 40 initial temperature history samples leading up to now
export function generateInitialTempHistory(): TempHistoryPoint[] {
  const points: TempHistoryPoint[] = [];
  const now = Date.now();
  for (let i = 39; i >= 0; i--) {
    const time = new Date(now - i * 15000);
    const minuteSec = time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
    
    // Smooth natural noise
    const nozzleNoise = (Math.sin(i * 0.4) * 0.7) + ((Math.random() - 0.5) * 0.4);
    const bedNoise = (Math.cos(i * 0.3) * 0.3) + ((Math.random() - 0.5) * 0.2);
    
    points.push({
      timestamp: time.toISOString(),
      timeLabel: minuteSec,
      nozzle: Number((210.0 + nozzleNoise).toFixed(1)),
      nozzleTarget: 210.0,
      bed: Number((60.0 + bedNoise).toFixed(1)),
      bedTarget: 60.0,
      chamber: Number((33.5 + Math.sin(i * 0.1) * 0.5).toFixed(1)),
    });
  }
  return points;
}
